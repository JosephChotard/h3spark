"""
Generates the type stubs for the registry-generated modules (h3spark.native, h3spark.udf, h3spark.hex), whose
functions type checkers can't otherwise see. Run after adding or changing a function:

    uv run python scripts/gen_stubs.py

test/test_stubs.py fails if the committed stubs are out of date.
"""

import inspect
import typing
from enum import Enum
from pathlib import Path

import black
from pyspark.sql.column import Column

import h3spark.hex
import h3spark.native
import h3spark.udf
from h3spark import REGISTRY
from h3spark._registry import H3Function

UDF_DOC = "Python UDF backed by h3-py. Cells may be long or hex strings."
PACKAGE = Path(__file__).resolve().parents[1] / "src" / "h3spark"
HEADER = '''"""{doc}"""

# Generated by scripts/gen_stubs.py, do not edit.

from pyspark.sql.column import Column

from h3spark._registry import ColumnOrName
from h3spark.models import AreaUnit, LengthUnit

__all__ = {names!r}
'''


def render_annotation(annotation) -> str:
    args = typing.get_args(annotation) or (annotation,)
    names = [a.__name__ for a in args if a not in (Column, str)]
    if Column in args:
        names.append("ColumnOrName")
    elif str in args:
        names.append("str")
    return " | ".join(names)


def render_default(default) -> str:
    if isinstance(default, Enum):
        return f"{type(default).__name__}.{default.name}"
    return repr(default)


def render_function(
    name: str, entry: H3Function, doc: str, returns: str, own_doc: bool = True
) -> str:
    params = []
    for param in entry.signature.parameters.values():
        rendered = f"{param.name}: {render_annotation(param.annotation)}"
        if param.default is not inspect.Parameter.empty:
            rendered += f" = {render_default(param.default)}"
        params.append(rendered)
    own = inspect.cleandoc(entry.default.__doc__ or "") if own_doc else ""
    docstring = "\n\n".join(filter(None, [doc, own]))
    docstring = f"{docstring}\n\nReturns: Column[{returns}]".replace("\n", "\n    ")
    return f'def {name}({", ".join(params)}) -> Column:\n    """{docstring}\n    """\n'


def render_module(module, functions: dict[str, tuple]) -> str:
    doc = inspect.cleandoc(module.__doc__).split("\n\n")[0]
    parts = [HEADER.format(doc=doc, names=sorted(functions))]
    parts += [render_function(name, *functions[name]) for name in sorted(functions)]
    return black.format_str("\n".join(parts), mode=black.Mode(is_pyi=True))


def render() -> dict[str, str]:
    """Stub file name -> contents"""
    native_names = {name: name for name in REGISTRY if REGISTRY[name].native}
    native_names.update(h3spark.native.ALIASES)
    hex_types = {"cell": "string", "cells": "array<string>"}

    def type_of(entry: H3Function) -> str:
        return entry.return_type.simpleString()

    return {
        "native.pyi": render_module(
            h3spark.native,
            {
                alias: (
                    REGISTRY[name],
                    "Native Spark implementation.",
                    type_of(REGISTRY[name]),
                )
                for alias, name in native_names.items()
            },
        ),
        "udf.pyi": render_module(
            h3spark.udf,
            {
                # The docstrings of natively implemented functions describe the native version
                name: (entry, UDF_DOC, type_of(entry), entry.native is None)
                for name, entry in REGISTRY.items()
            },
        ),
        "hex.pyi": render_module(
            h3spark.hex,
            {
                name: (
                    entry,
                    f"Hex string version of h3spark.{name}: cell arguments are hex string columns.",
                    hex_types.get(entry.returns, type_of(entry)),
                )
                for name, entry in REGISTRY.items()
                if entry.hex
            },
        ),
    }


def main():
    for name, contents in render().items():
        (PACKAGE / name).write_text(contents)
        print(f"Wrote {PACKAGE / name}")


if __name__ == "__main__":
    main()
